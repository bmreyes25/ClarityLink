"""CL-HONDA-111-01: pin the VideoConfig (opcode 1) policy per framing profile.

The evidence is in conflict (evidence-map C2): Honda's own Type110 receiver
passes opcode-1 bodies through the same CTR context as video, while the pinned
external Type111 receivers treat the config as clear. The receiver must not
silently pick a side for Honda. These tests document the three-way behavior so a
change to it is deliberate:

  * Honda-Type110 framing applied to the secondary: opcode 1 is refused.
  * The legacy Type111 prior-art profile: framing itself needs evidence.
  * The current-iOS profile: config is read clear and does not consume the
    protected-frame counter.

Synthetic generated bytes only. Nothing here is Honda Type111 evidence.
"""
from __future__ import annotations

import os
import socket
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src" / "claritylink-jmcs"))

from claritylink_jmcs.media import FramingProfile, encode_lab_message
from claritylink_jmcs.receiver import Receiver, ReceiverError, ReceiverState
from claritylink_jmcs.security import ModernChaChaScreenSecurity

REQUEST = {"streams": [{"type": 110, "streamConnectionID": 11},
                       {"type": 111, "streamConnectionID": 12}]}
CONFIG_BODY = b"xxxxavcC" + bytes([1, 66, 0, 30, 255, 225, 0, 2, 0x67, 0x42, 1, 0, 2, 0x68, 0xCE])


def _started(receiver: Receiver) -> int:
    generation = receiver.start_session()
    receiver.info_exchanged(generation)
    receiver.setup(REQUEST, generation)
    return generation


def test_honda_type110_framing_on_the_secondary_refuses_video_config_and_keeps_the_primary():
    receiver = Receiver(clear_lab=True)   # default profile: Honda Type110 framing
    assert receiver.framing_profile == FramingProfile.LEGACY_HONDA_TYPE110
    generation = _started(receiver)
    with socket.create_connection(("127.0.0.1", receiver.secondary.port), timeout=1) as client:
        receiver.accept_secondary(generation)
        client.sendall(encode_lab_message(1, CONFIG_BODY))
        with pytest.raises(ReceiverError, match="video_config_not_implemented"):
            receiver.receive_secondary_frame(generation)
    assert receiver.state is ReceiverState.PRIMARY_ACTIVE
    assert receiver.snapshot().secondary_listeners == 0
    receiver.teardown(generation)
    assert receiver.snapshot().sessions == 0


def test_legacy_type111_prior_art_framing_is_refused_for_lack_of_honda_evidence():
    receiver = Receiver(clear_lab=True, framing_profile=FramingProfile.LEGACY_TYPE111_PRIOR_ART)
    generation = _started(receiver)
    with socket.create_connection(("127.0.0.1", receiver.secondary.port), timeout=1) as client:
        receiver.accept_secondary(generation)
        client.sendall(encode_lab_message(1, CONFIG_BODY))
        with pytest.raises(ReceiverError, match="type111_framing_evidence_required"):
            receiver.receive_secondary_frame(generation)
    assert receiver.state is ReceiverState.PRIMARY_ACTIVE
    receiver.teardown(generation)


def test_current_ios_profile_reads_config_clear_and_leaves_the_protected_counter_alone():
    key = os.urandom(32)
    receiver = Receiver(framing_profile=FramingProfile.CURRENT_IOS_TYPE111,
                        security_factory=lambda: ModernChaChaScreenSecurity(key, provenance="generated fixture"))
    generation = _started(receiver)
    header = bytearray(128)
    header[:4] = len(CONFIG_BODY).to_bytes(4, "little")
    header[4] = 1
    with socket.create_connection(("127.0.0.1", receiver.secondary.port), timeout=1) as client:
        receiver.accept_secondary(generation)
        client.sendall(bytes(header) + CONFIG_BODY)
        assert receiver.receive_secondary_frame(generation) == b""
    assert "VIDEO_CONFIG_RECEIVED" in receiver.events
    assert receiver.security.counter == 0   # config did not consume the AEAD counter
    assert receiver.state is ReceiverState.BOTH_ACTIVE
    receiver.teardown(generation)


def test_no_default_profile_carries_honda_type111_security_or_config_protection():
    # A receiver built without an explicit security provider cannot decode any
    # Type111 media, whatever the framing profile: the evidence gate stays closed.
    receiver = Receiver(framing_profile=FramingProfile.CURRENT_IOS_TYPE111)
    generation = receiver.start_session()
    receiver.info_exchanged(generation)
    response = receiver.setup(REQUEST, generation)
    assert [x["type"] for x in response.fields["streams"]] == [110]   # 111 not admitted
    assert receiver.secondary is None
    receiver.teardown(generation)
